const express = require("express");
const protect = require("../middleware/authMiddleware");
const optionalAuth = require("../middleware/optionalAuth");
const requireRoles = require("../middleware/requireRoles");
const c = require("../controllers/paymentController");
const router = express.Router();
router.post("/webhook", c.paymentWebhook);
router.post("/", optionalAuth, c.createPayment);
router.get("/my-payments", protect, c.getMyPayments);
router.get("/admin/recent", protect, requireRoles("admin", "superadmin"), c.getAdminPayments);
router.get("/:id", protect, c.getPaymentById);
router.put("/:id/status", protect, c.updatePaymentStatus);
module.exports = router;
