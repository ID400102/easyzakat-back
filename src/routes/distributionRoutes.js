const express = require("express");
const protect = require("../middleware/authMiddleware");
const requireRoles = require("../middleware/requireRoles");
const c = require("../controllers/distributionController");
const router = express.Router();
router.use(protect, requireRoles("admin", "superadmin"));
router.get("/", c.getDistributions);
router.post("/", c.createDistribution);
router.put("/:id/status", c.updateDistributionStatus);
router.delete("/:id", c.deleteDistribution);
module.exports = router;
